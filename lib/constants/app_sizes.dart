/// Shared spacing values in logical pixels for padding and gaps.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 48;
}

/// Shared font sizes in logical pixels, named by their intended role.
abstract final class AppFontSizes {
  static const double caption = 12;
  static const double label = 14;
  static const double text = 16;
  static const double subtitle = 20;
  static const double title = 24;
  static const double heading = 32;
  static const double display = 48;
}
